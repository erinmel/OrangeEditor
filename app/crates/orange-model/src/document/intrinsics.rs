pub(crate) fn is_intrinsic_definition(id: &str) -> bool {
    matches!(
        id,
        "core/call"
            | "core/function-entry"
            | "core/function-outputs"
            | "core/return"
            | "core/get-variable"
            | "core/set-variable"
            | "core/update-variable"
            | "core/set-shared"
            | "core/update-shared"
            | "core/on-event"
            | "core/emit"
            | "core/branch"
            | "core/switch"
            | "core/sequence"
            | "core/fork"
            | "core/for-each"
            | "core/count"
            | "core/while"
            | "core/break"
            | "core/continue"
            | "core/gate"
            | "core/do-once"
            | "core/flip-flop"
            | "core/yield"
            | "core/wait"
            | "core/await-event"
            | "core/register"
            | "core/select"
            | "core/and"
            | "core/or"
            | "core/coalesce"
            | "core/try"
            | "core/match-result"
            | "core/repeat-begin"
            | "core/repeat-end"
            | "core/map-begin"
            | "core/map-end"
            | "core/fold-begin"
            | "core/fold-end"
            | "core/filter-begin"
            | "core/filter-end"
    )
}
